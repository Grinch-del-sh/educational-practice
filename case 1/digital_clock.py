def format_number(number):
    """
    Форматирует число в строку из 2 символов
    """
    return f"{number:02d}"

def print_digital_clock(day, month, year):
    """
    Функция для отображения даты в формате электронного табло
    """
    # Форматируем числа в строки из 2 символов
    day_str = format_number(day)
    month_str = format_number(month)
    year_str = format_number(year % 100)  # Берем последние 2 цифры года
    
    # Создаем списки цифр для каждой части даты
    day_digits = [DIGITS[digit] for digit in day_str]
    month_digits = [DIGITS[digit] for digit in month_str]
    year_digits = [DIGITS[digit] for digit in year_str]
    
    # Выводим каждую строку табло
    for i in range(5):
        # День
        print(' '.join([digit[i] for digit in day_digits]), end=' ')
        # Месяц
        print(' '.join([digit[i] for digit in month_digits]), end=' ')
        # Год
        print(' '.join([digit[i] for digit in year_digits]))

